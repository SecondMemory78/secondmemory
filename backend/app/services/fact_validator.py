"""Валидатор извлечённых значений.

Зачем он нужен. Разбор ищет слово-синоним и берёт ближайшее число. На бланке
анализа это работает, на повествовательном заключении — нет. Живой пример из
КТ почек: система создала четыре показателя, и все четыре были неверны.

    «Эффективная доза: 18 мЗв»          → «Разовая доза 18»
    «кисты до 10×9 мм»                  → «Данные ПРИ 10»
    «плотность содержимого кист 15 HU»  → «Плотность конкремента 15 HU»
    «кисты размерами до 37×31 мм»       → «Локализация конкремента 37»

Причём в том же документе прямо написано, что конкрементов НЕТ.

Валидатор стоит между разбором и записью и отвечает на один вопрос: имеет ли
это значение право стать фактом. Он не угадывает и ничего не исправляет — он
только отклоняет. Пропустить значение не страшно, врач внесёт руками.
Выдумать — страшно: врач подтвердит не глядя, и в карте появится камень,
которого нет.

Работает независимо от того, кто извлёк значение — правила или модель.
"""
from __future__ import annotations

import re
from typing import Any, Optional

# ── 1. Тип значения берём из справочника, а не из своего списка ─────────────
# У каждого из 279 параметров там уже указан value_type: «число», «справочник»,
# «структурированный текст» и так далее. Свой список я бы вёл руками и
# неизбежно забыл половину — а справочник ведётся вместе с параметрами.
NON_NUMERIC_TYPES = {
    "справочник", "категория", "классификация", "текст",
    "структурированный текст", "структура", "список", "ссылка",
    "множественный выбор", "UUID",
}


def _value_type(code: str) -> str:
    from ..reference_data import parameters
    for x in parameters():
        if x.get("code") == code:
            return x.get("value_type", "")
    return ""

# ── 2. Категориальные шкалы ─────────────────────────────────────────────────
# После слова Bosniak должно стоять I/II/IIF/III/IV, а не произвольный символ.
CATEGORICAL = {
    "bosniak": re.compile(r"^(I{1,3}|IV|IIF)(\s*[–—-]\s*(I{1,3}|IV|IIF))?$", re.I),
    "pirads": re.compile(r"^[1-5]$"),
    "isup": re.compile(r"^[1-5]$"),
    "gleason": re.compile(r"^\d\s*\+\s*\d(\s*=\s*\d+)?$"),
}

# ── 3. Технические параметры исследования ───────────────────────────────────
# Доза облучения, номер серии, объём контраста — это про аппарат, а не про
# пациента. В клиническую динамику они не идут никогда.
TECHNICAL_UNITS = {"мзв", "мsv", "msv", "мкзв", "кв", "мас", "mas", "kv"}
TECHNICAL_WORDS = ("эффективная доза", "лучевая нагрузка", "номер серии",
                   "серия", "скан", "kv", "mas", "объём контраста",
                   "количество контраста", "толщина среза")

# ── 4. Допустимые единицы для показателей, где единица однозначна ───────────
# Плотность бывает только в HU; доза препарата — никогда.
UNIT_WHITELIST = {
    "stone_density": {"hu"},
    "psa_total": {"нг/мл", "ng/ml"},
    "psa_free": {"нг/мл", "ng/ml"},
    "creatinine": {"мкмоль/л", "umol/l", "мг/дл", "mg/dl"},
    "hemoglobin": {"г/л", "g/l"},
}

# ── 5. Отрицания ────────────────────────────────────────────────────────────
NEGATIONS = ("не выявлен", "не выявлено", "не определя", "не содержит",
             "не обнаружен", "данных за", "не получено", "без признаков",
             "отсутств", "не расширен", "роста нет", "отрицательн")

# Что именно отрицание запрещает создавать: слово в тексте → коды показателей
NEGATION_BLOCKS = {
    "конкремент": ("stone_density", "stone_size", "stone_location", "stone_count"),
    "камн": ("stone_density", "stone_size", "stone_location", "stone_count"),
    "роста": ("culture_growth", "organism"),
}


class Rejected(Exception):
    """Значение не имеет права стать фактом. В сообщении — причина для врача."""


def _norm_unit(u: str) -> str:
    return (u or "").strip().lower().replace(" ", "")


def check(value: dict, context_line: str = "", full_text: str = "") -> Optional[str]:
    """Проверяет одно извлечённое значение.

    Возвращает причину отклонения или None, если значение допустимо.
    Причина пишется словами врача: она попадёт в панель исключённого.
    """
    code = (value.get("parameter_code") or "").lower()
    num = value.get("value_num")
    unit = _norm_unit(value.get("unit", ""))
    line = (context_line or "").lower()

    # 1. Параметр не может быть числом — проверяем по справочнику
    vtype = _value_type(value.get("parameter_code") or "")
    if num is not None and vtype in NON_NUMERIC_TYPES:
        return (f"это {vtype}, а не число — разбор взял соседнюю цифру "
                f"из текста")

    # 2. Технические параметры исследования
    if unit in TECHNICAL_UNITS:
        return "это технический параметр исследования, а не показатель пациента"
    if any(w in line for w in TECHNICAL_WORDS):
        return "строка описывает параметры аппарата, а не состояние пациента"

    # 3. Единица не подходит показателю
    allowed = UNIT_WHITELIST.get(code)
    if allowed and unit and unit not in {_norm_unit(a) for a in allowed}:
        return (f"единица «{value.get('unit')}» не бывает у этого показателя "
                f"(ожидается {', '.join(sorted(allowed))})")

    # 4. Отрицание в том же предложении или абзаце
    blocked = negated_codes(full_text or line)
    if code in blocked:
        return "в документе сказано, что этого нет — значение не может относиться к нему"

    # 5. Число без единицы там, где единица обязательна
    if num is not None and allowed and not unit:
        return "не указана единица измерения — значение не сохраняем вслепую"

    # 6. Голое число без основания в тексте. Если разбор не может показать
    #    фразу, из которой взял значение, то и факта нет: по ТЗ ссылка на
    #    фрагмент обязательна, иначе врачу нечего проверять.
    if num is not None and not (value.get("source_span") or "").strip():
        return "нет фразы-основания в документе — проверить значение нечем"

    return None


def negated_codes(text: str) -> set:
    """Какие показатели запрещены отрицаниями в тексте.

    Смотрим по предложениям: «конкрементов не содержит» в одном предложении
    запрещает камни, даже если двумя строками ниже стоит число.
    """
    low = (text or "").lower()
    out: set = set()
    for sentence in re.split(r"[.;\n]", low):
        if not any(n in sentence for n in NEGATIONS):
            continue
        for word, codes in NEGATION_BLOCKS.items():
            if word in sentence:
                out.update(codes)
    return out


def check_categorical(scale: str, raw: str) -> Optional[str]:
    """Проверка шкалы: Bosniak, PI-RADS, ISUP, Gleason.

    Если значение не из словаря — это ошибка чтения, а не редкий случай.
    Исправлять «на самое похожее» нельзя: врач должен увидеть сомнение.
    """
    rx = CATEGORICAL.get((scale or "").lower())
    if not rx:
        return None
    if not rx.match((raw or "").strip()):
        return (f"«{raw}» не входит в допустимые значения {scale} — "
                f"нужна проверка по исходному документу")
    return None
