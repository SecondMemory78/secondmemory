// Распознавание жеста «листнуть».
//
// Вынесено отдельно от компонента, чтобы это можно было проверить без браузера:
// в обучении жест уже один раз «не работал», и ловить такое руками на телефоне
// дорого.
//
// Правила простые:
//  • короткое движение — это не жест, а дрожь пальца при нажатии;
//  • если палец ушёл больше по вертикали, чем по горизонтали, человек прокручивал
//    текст внутри карточки, а не листал.

export const SWIPE_MIN = 48;          // пикселей по горизонтали
export const SWIPE_RATIO = 1.5;       // во столько раз горизонталь должна превышать вертикаль

/** Возвращает 1 (вперёд), -1 (назад) или 0 (не жест). */
export function swipeDirection(from, to, opts = {}) {
  if (!from || !to) return 0;
  const min = opts.min ?? SWIPE_MIN;
  const ratio = opts.ratio ?? SWIPE_RATIO;
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  if (Math.abs(dx) < min) return 0;
  if (Math.abs(dx) < Math.abs(dy) * ratio) return 0;
  return dx < 0 ? 1 : -1;             // палец влево — следующий экран
}
