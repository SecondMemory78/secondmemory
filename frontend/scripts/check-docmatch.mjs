// Проверка поиска фразы-основания без браузера.
//
// Подсветку «находка → фрагмент исходника» глазами не проверить: демо-
// распознаватель отдаёт бланк без повествовательных находок. А ошибка здесь
// тихая — врач нажмёт и ничего не увидит.

import { findSpan, skeleton } from "../src/lib/docmatch.js";

const CT = `- правая почка несколько увеличена за счет множественных полиморфных кист
размерами до 40х32мм, с однородным содержимым, (в единичных кистах более
плотное содержимое +93HU, остальные с плотностью до 15HU);
- левая почка несколько увеличена за счет кист размерами до 37х31мм;
Заключение: КТ-картина поликистоза (Bosniak I-II).`;

const cases = [
  ["фраза с переносом строки находится", CT, "кист размерами до 40х32мм", true],
  ["разные пробелы не мешают", CT, "кист  размерами   до 40х32 мм", true],
  ["скобки и плюсы не мешают", CT, "плотное содержимое 93HU", true],
  ["левая почка отличается от правой", CT, "кист размерами до 37х31мм", true],
  ["чего нет в тексте — не находится", CT, "конкремент плотностью 920 HU", false],
  ["пустая фраза ничего не подсвечивает", CT, "", false],
];

let bad = 0;
for (const [name, text, phrase, expected] of cases) {
  const got = findSpan(text, phrase);
  if (Boolean(got) !== expected) { bad++; console.log("ПРОВАЛ:", name, "→", got); }
}

const span = findSpan(CT, "кист размерами до 37х31мм");
if (span) {
  const got = skeleton(CT.slice(span.from, span.to));
  if (!got.includes(skeleton("37х31"))) {
    bad++; console.log("ПРОВАЛ: подсвечен не тот кусок:", CT.slice(span.from, span.to));
  }
  if ((span.to - span.from) > "кист размерами до 37х31мм".length + 12) {
    bad++; console.log("ПРОВАЛ: подсветка захватила лишнее");
  }
} else { bad++; console.log("ПРОВАЛ: фраза левой почки не нашлась"); }

console.log(bad === 0 ? "Всё верно." : `Ошибок: ${bad}`);
process.exit(bad === 0 ? 0 : 1);
