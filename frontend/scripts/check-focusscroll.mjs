// Проверка прокрутки к полю без браузера.
//
// Клавиатуру в headless-браузере не вызвать, а ошибка тут тихая: врач нажимает
// на поле и не видит, куда печатает. Поэтому решающую часть — «закрыто ли поле
// видимой областью» — вынесли в чистую функцию и проверяем её.

// Берём ту же функцию, что работает в приложении. Копия здесь была бы
// проверкой копии: разойдутся — и проверка останется зелёной.
import { isHiddenByKeyboard as hidden } from "../src/lib/focusscroll.js";

const cases = [
  ["поле у низа экрана, клавиатуры нет", 800, 844, false],
  ["поле под клавиатурой", 800, 544, true],
  ["поле ровно на границе запаса", 532, 544, false],
  ["поле чуть ниже границы", 540, 544, true],
  ["поле в середине экрана", 300, 544, false],
];

let bad = 0;
for (const [name, bottom, visible, expected] of cases) {
  const got = hidden(bottom, visible);
  if (got !== expected) { bad++; console.log("ПРОВАЛ:", name, "→", got); }
}
console.log(bad === 0 ? "Всё верно." : `Ошибок: ${bad}`);
process.exit(bad === 0 ? 0 : 1);
