// Названия разделов должны совпадать с подписями в меню, иначе врач ищет по
// памятке то, чего в интерфейсе нет: «эпизода», «Входящих» и «Сегодня» у нас
// на экранах не написано.
const MEMO = [
  ["Добавить", "«Пациенты» → карта → фото, голос или текст"],
  ["Найти", "поиск сверху или спросить ассистента"],
  ["Изменить", "открыть значение → исправить → подтвердить"],
  ["Не забыть", "«Главная» и «Задачи» — просроченное подсвечено"],
  ["Вечером", "закрыть выполненное и перенести оставшееся"],
];

export default function Onboarding({ onDone }) {
  const [step, setStep] = useState(0);       // 0..N-1 экраны, N — памятка
  const [busy, setBusy] = useState(false);
  const total = SCREENS.length;
  const onMemo = step >= total;
  const last = onMemo ? total : step;        // индекс последней точки

  // Листание пальцем. Кнопки «Назад» и «Далее» остаются — жест их дополняет,
  // а не заменяет: на компьютере мыши жеста нет.
  const touch = useRef(null);
  function onTouchStart(e) {
    const t = e.touches[0];
    touch.current = { x: t.clientX, y: t.clientY };
  }
  function onTouchEnd(e) {
    const from = touch.current;
    touch.current = null;
    const t = e.changedTouches && e.changedTouches[0];
    if (!from || !t) return;
    const dir = swipeDirection(from, { x: t.clientX, y: t.clientY });
    if (dir) go(dir);
  }

  function go(delta) {
    const next = step + delta;
    if (next < 0 || next > total) return;    // за края не уходим
    if (next === 0 && step === 1) return;    // с первого шага назад на заставку не возвращаем
    setStep(next);
  }

  async function start() {
    // «Начать на примере» — создаём учебного пациента (идемпотентно на бэке)
    setBusy(true);
    try { await api.sandboxStart(); } catch { /* не блокируем обучение из-за сети */ }
    setBusy(false);
    setStep(1);
  }

  async function finish() {
    setBusy(true);
    try { await api.sandboxFinish(true); } catch { /* прогресс всё равно закроем локально */ }
    setBusy(false);
    onDone?.();
  }

  async function skip() {
    setBusy(true);
    try { await api.sandboxFinish(false); } catch { /* игнор */ }
    setBusy(false);
    onDone?.();
  }

  const s = SCREENS[Math.min(step, total - 1)];

  return (
    <div className="ob-overlay" role="dialog" aria-modal="true" aria-label="Обучение">
      <div className="ob-card" onTouchStart={onTouchStart} onTouchEnd={onTouchEnd}>
        <div className="ob-top">
          <span className="ob-count muted">
            {onMemo ? "Памятка" : `Шаг ${step + 1} из ${total}`}
          </span>
          {!onMemo && (
            <button className="ob-skip muted" onClick={skip} disabled={busy}>Пропустить</button>
          )}
        </div>

        {!onMemo ? (
          <>
            <h2 className="ob-title">{s.title}</h2>
            <p className="ob-body">{s.body}</p>
            {s.hint && <p className="ob-hint">{s.hint}</p>}
          </>
        ) : (
          <>
            <h2 className="ob-title">Памятка после обучения</h2>
            <div className="ob-memo">
              {MEMO.map(([k, v]) => (
                <div className="ob-memo-row" key={k}>
                  <b>{k}:</b> <span>{v}</span>
                </div>
              ))}
            </div>
            <p className="ob-hint">Всё это всегда под рукой в разделе «Помощь» — там же можно повторить обучение.</p>
          </>
        )}

        <div className="ob-dots" role="tablist" aria-label="Шаги обучения">
          {SCREENS.map((_, i) => (
            <button key={i} className={"ob-dot" + (i === last ? " on" : "")}
                    aria-label={`Шаг ${i + 1}`} aria-selected={i === last}
                    onClick={() => step > 0 && setStep(i)} />
          ))}
          <span className={"ob-dot" + (onMemo ? " on" : "")} />
        </div>

        <div className="ob-nav">
          {step === 0 && (
            <button className="btn pri block ob-cta" onClick={start} disabled={busy}>
              Начать на примере
            </button>
          )}
          {step > 0 && !onMemo && (
            <>
              <button className="btn" onClick={() => setStep(step - 1)} disabled={busy}>Назад</button>
              <button className="btn pri" onClick={() => setStep(step + 1)} disabled={busy}>Далее</button>
            </>
          )}
          {onMemo && (
            <>
              <button className="btn" onClick={() => setStep(total - 1)} disabled={busy}>Назад</button>
              <button className="btn pri" onClick={finish} disabled={busy}>Готово</button>
            </>
          )}
        </div>
      </div>
    </div>
  );
}
