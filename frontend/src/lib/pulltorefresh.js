// «Потянуть вниз, чтобы обновить».
//
// Зачем. Врач свернул приложение, вернулся через час — на экране вчерашние
// данные. Обновить можно было только перезагрузкой страницы, а это в
// установленном приложении вообще не очевидно.
//
// Правила, которые здесь важнее кода:
//  • жест работает ТОЛЬКО когда список уже прокручен в самый верх. Иначе врач,
//    листая вверх по длинному списку, каждый раз вызывал бы обновление;
//  • тянуть надо заметно: случайное касание не должно дёргать экран;
//  • пока обновляем — показываем это, иначе человек тянет ещё раз.

export const PULL_TRIGGER = 70;    // пикселей, после которых жест считается
export const PULL_MAX = 110;       // дальше не растягиваем: это не резинка

/** Насколько показать подсказку при оттягивании на dy пикселей. */
export function pullProgress(dy) {
  if (dy <= 0) return 0;
  return Math.min(1, dy / PULL_TRIGGER);
}

/** Сработал ли жест. */
export function pullTriggered(dy) {
  return dy >= PULL_TRIGGER;
}

/** Смещение содержимого: тянется всё медленнее, чтобы чувствовался предел. */
export function pullOffset(dy) {
  if (dy <= 0) return 0;
  return Math.min(PULL_MAX, dy * 0.5);
}
