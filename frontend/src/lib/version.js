//   • от лица пользы, а не работы: «приёмы больше не теряются», а не
//     «исправлен счётчик приёмов»;
//   • конкретно: что именно стало иначе и где это увидеть;
//   • честно про ограничения: если что-то работает не везде — так и пишем;
//   • без похвальбы и без слов «улучшено», «оптимизировано», «доработано» —
//     они не несут смысла;
//   • три-семь строк на версию. Длинный список никто не читает.
