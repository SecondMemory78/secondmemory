// Смахивание строки списка.
//
// Жест спорный, поэтому правила строже обычных:
//  • тянуть надо заметно — случайное движение при прокрутке не должно ничего
//    делать;
//  • вертикаль побеждает: если палец ушёл вниз сильнее, чем вбок, человек
//    листает список, а не смахивает строку;
//  • действие выполняется, только если строку увели ДОСТАТОЧНО далеко. Иначе
//    строка возвращается на место — и это тоже результат, а не «не сработало»;
//  • разрушительное действие (удалить) требует большего пути, чем обычное.
//    Промахнуться и удалить заметку нельзя.

export const ACTION_MIN = 64;        // обычное действие
export const DESTRUCTIVE_MIN = 104;  // удаление — дальше

/** Насколько строка уехала за пальцем. Сопротивление, чтобы чувствовался предел. */
export function rowOffset(dx, max = 140) {
  const sign = dx < 0 ? -1 : 1;
  return sign * Math.min(max, Math.abs(dx) * 0.85);
}

/** Считается ли жест смахиванием, а не прокруткой. */
export function isSwipe(dx, dy, min = 16) {
  return Math.abs(dx) >= min && Math.abs(dx) > Math.abs(dy) * 1.3;
}

/** Что сделать, когда палец отпущен: "" | "right" | "left".
 *
 *  ВЛЕВО — выполнить: это короткое движение к себе, им пользуются часто.
 *  ВПРАВО — удалить, и путь для него ДЛИННЕЕ: промахнуться и стереть задачу
 *  нельзя.
 *
 *  Пороги привязаны к смыслу действия, а не к стороне: обычное действие — 64,
 *  разрушительное — 104. Поменяем стороны местами снова — пороги поедут за
 *  ними сами.
 */
export function resolveAction(dx, dy) {
  if (!isSwipe(dx, dy)) return "";
  if (dx < 0) return -dx >= ACTION_MIN ? "left" : "";        // влево — выполнить
  return dx >= DESTRUCTIVE_MIN ? "right" : "";               // вправо — удалить
}
